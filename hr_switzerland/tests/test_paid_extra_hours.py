from datetime import date

from odoo import Command
from odoo.tests import TransactionCase, freeze_time


class TestPaidExtraHours(TransactionCase):
    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        attendances = []
        for day in "01234":
            for period, hour_from, hour_to in (
                ("morning", 8, 12),
                ("afternoon", 13, 17),
            ):
                attendances.append(
                    (
                        0,
                        0,
                        {
                            "name": f"{day} {period}",
                            "dayofweek": day,
                            "day_period": period,
                            "hour_from": hour_from,
                            "hour_to": hour_to,
                            "date_from": date(2020, 1, 1),
                        },
                    )
                )
        cls.calendar = cls.env["resource.calendar"].create(
            {"name": "Dated calendar", "attendance_ids": attendances}
        )
        cls.employee = cls.env["hr.employee"].create(
            {"name": "Overtime Employee", "resource_calendar_id": cls.calendar.id}
        )
        cls.paid_type = cls.env["hr.leave.type"].create(
            {
                "name": "Paid Extra Hours",
                "requires_allocation": "yes",
                "employee_requests": "no",
                "overtime_deductible": True,
                "request_unit": "hour",
            }
        )

    def test_hours_per_day_dated_calendar(self):
        """A calendar with only dated attendances has its hours per day."""
        self.assertEqual(self.calendar.stored_hours_per_day, 8)

    def test_hours_per_day_refreshed_when_period_starts(self):
        """A rate change planned in advance is applied when its period starts,
        without any change on the calendar."""
        Calendar = self.env["resource.calendar"]
        attendances = []
        for day in "01234":
            # 8h per day until the end of 2026, then 4h per day
            attendances += [
                Command.create(
                    {
                        "name": f"{day} {period}",
                        "dayofweek": day,
                        "day_period": period,
                        "hour_from": hour_from,
                        "hour_to": hour_to,
                        "date_from": date(2020, 1, 1),
                        "date_to": date(2026, 12, 31),
                    }
                )
                for period, hour_from, hour_to in (
                    ("morning", 8, 12),
                    ("afternoon", 13, 17),
                )
            ]
            attendances.append(
                Command.create(
                    {
                        "name": f"{day} morning part time",
                        "dayofweek": day,
                        "day_period": "morning",
                        "hour_from": 8,
                        "hour_to": 12,
                        "date_from": date(2027, 1, 1),
                    }
                )
            )
        with freeze_time("2026-12-31"):
            # Like the calendars generated by hr_employee_calendar_planning
            calendar = Calendar.create(
                {
                    "name": "Planned rate change",
                    "attendance_ids": attendances,
                    "active": False,
                    "auto_generate": True,
                }
            )
            self.assertEqual(calendar.stored_hours_per_day, 8)
            self.assertNotIn(calendar, Calendar._cron_refresh_dated_hours_per_day())
        with freeze_time("2027-01-01"):
            self.assertIn(calendar, Calendar._cron_refresh_dated_hours_per_day())
            self.assertEqual(calendar.stored_hours_per_day, 4)

    def _planned_calendar(self, periods):
        """periods: (date_from, date_to, [(hour_from, hour_to), ...])"""
        attendances = [
            Command.create(
                {
                    "name": f"{day} {hour_from}",
                    "dayofweek": day,
                    "day_period": "morning" if hour_from < 12 else "afternoon",
                    "hour_from": hour_from,
                    "hour_to": hour_to,
                    "date_from": date_from,
                    "date_to": date_to,
                }
            )
            for date_from, date_to, hours in periods
            for day in "01234"
            for hour_from, hour_to in hours
        ]
        return self.env["resource.calendar"].create(
            {"name": "Planning", "attendance_ids": attendances, "active": False}
        )

    def _hours_per_day_on(self, calendar, day):
        return calendar._get_hours_per_day(calendar._get_current_dated_attendances(day))

    def test_hours_per_day_outside_periods(self):
        """Before the planning starts or in a gap: next period. After it: last."""
        full, six, half = [(8, 12), (13, 17)], [(8, 12), (13, 15)], [(8, 12)]
        calendar = self._planned_calendar(
            [
                (date(2027, 1, 1), date(2027, 6, 30), full),
                (date(2027, 9, 1), date(2027, 12, 31), six),
                (date(2028, 1, 1), date(2028, 12, 31), half),
            ]
        )
        self.assertEqual(self._hours_per_day_on(calendar, date(2026, 12, 1)), 8)
        self.assertEqual(self._hours_per_day_on(calendar, date(2027, 3, 1)), 8)
        self.assertEqual(self._hours_per_day_on(calendar, date(2027, 7, 15)), 6)
        self.assertEqual(self._hours_per_day_on(calendar, date(2028, 3, 1)), 4)
        self.assertEqual(self._hours_per_day_on(calendar, date(2029, 3, 1)), 4)

    def test_paid_extra_hours_in_report(self):
        """Extra hours removed by an allocation are in the theoretical report,
        other adjustments are not."""
        report = self.env["hr.attendance.theoretical.time.report"]
        self.env["hr.attendance.overtime"].create(
            {
                "employee_id": self.employee.id,
                "date": date(2024, 6, 30),
                "adjustment": True,
                "duration": 20,
            }
        )
        allocation = self.env["hr.leave.allocation"].create(
            {
                "name": "Paid",
                "employee_id": self.employee.id,
                "holiday_status_id": self.paid_type.id,
                "number_of_days": 5 / 8,
                "date_from": date(2026, 10, 31),
            }
        )
        self.assertEqual(allocation.number_of_hours_display, 5)
        self.assertEqual(allocation.overtime_id.duration, -5)
        self.assertEqual(self.employee.total_overtime, 15)
        self.env.flush_all()
        lines = report.search([("employee_id", "=", self.employee.id)])
        self.assertEqual(lines.date, date(2026, 10, 31))
        self.assertEqual(sum(lines.mapped("difference")), -5)

    def test_negative_extra_hours_in_my_time(self):
        """The extra hours card is shown in "My Time" with a negative balance."""
        extra_type = self.env["hr.leave.type"].create(
            {
                "name": "Extra Hours",
                "requires_allocation": "no",
                "overtime_deductible": True,
                "request_unit": "hour",
            }
        )
        self.env["hr.attendance.overtime"].create(
            {
                "employee_id": self.employee.id,
                "date": date(2026, 1, 1),
                "adjustment": True,
                "duration": -3,
            }
        )
        data = extra_type.get_allocation_data(self.employee)[self.employee]
        cards = [card for card in data if card[3] == extra_type.id]
        self.assertEqual(len(cards), 1)
        self.assertEqual(cards[0][1]["virtual_remaining_leaves"], -3)
