from datetime import date

from odoo import api, fields, models


class ResourceCalendar(models.Model):
    _inherit = "resource.calendar"

    @api.depends(
        "attendance_ids",
        "attendance_ids.hour_from",
        "attendance_ids.hour_to",
        "attendance_ids.date_from",
        "attendance_ids.date_to",
        "two_weeks_calendar",
        "flexible_hours",
    )
    def _compute_stored_hours_per_day(self):
        """The calendars generated by hr_employee_calendar_planning only have
        attendances limited by dates, which the core computation ignores: their
        hours per day was always 0. Time off and allocations in hours could not
        be converted to days (their duration was emptied). Use the attendances
        valid today, or the most recent period if none is valid anymore.
        """
        res = super()._compute_stored_hours_per_day()
        today = fields.Date.context_today(self)
        for calendar in self:
            if calendar.flexible_hours or calendar._get_global_attendances():
                continue
            calendar.stored_hours_per_day = calendar._get_hours_per_day(
                calendar._get_current_dated_attendances(today)
            )
        return res

    def _get_current_dated_attendances(self, day):
        self.ensure_one()
        attendances = self.attendance_ids.filtered(
            lambda a: (
                a.day_period != "lunch" and not a.resource_id and not a.display_type
            )
        )
        current = attendances.filtered(
            lambda a: (
                (not a.date_from or a.date_from <= day)
                and (not a.date_to or a.date_to >= day)
            )
        )
        if not current and attendances:
            last_start = max(a.date_from or date.min for a in attendances)
            current = attendances.filtered(
                lambda a: (a.date_from or date.min) == last_start
            )
        return current
