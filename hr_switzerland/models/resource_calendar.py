from datetime import date

from odoo import api, fields, models
from odoo.tools import float_compare


class ResourceCalendar(models.Model):
    _inherit = "resource.calendar"

    @api.depends(
        "attendance_ids",
        "attendance_ids.hour_from",
        "attendance_ids.hour_to",
        "attendance_ids.date_from",
        "attendance_ids.date_to",
        "two_weeks_calendar",
        "flexible_hours",
    )
    def _compute_stored_hours_per_day(self):
        """The calendars generated by hr_employee_calendar_planning only have
        attendances limited by dates, which the core computation ignores: their
        hours per day was always 0. Time off and allocations in hours could not
        be converted to days (their duration was emptied). Use the attendances
        valid today, or the most recent period if none is valid anymore.
        """
        res = super()._compute_stored_hours_per_day()
        today = fields.Date.context_today(self)
        for calendar in self:
            if calendar.flexible_hours or calendar._get_global_attendances():
                continue
            calendar.stored_hours_per_day = calendar._get_hours_per_day(
                calendar._get_current_dated_attendances(today)
            )
        return res

    @api.model
    def _cron_refresh_dated_hours_per_day(self):
        """The hours per day of the planned calendars depend on the period valid
        today: refresh them when a new period starts (rate change planned in
        advance), the calendar itself is not modified at that moment.
        The calendars generated by hr_employee_calendar_planning are archived."""
        today = fields.Date.context_today(self)
        to_refresh = (
            self.with_context(active_test=False)
            .search([("flexible_hours", "=", False)])
            .filtered(
                lambda c: not c._get_global_attendances()
                and float_compare(
                    c.stored_hours_per_day,
                    c._get_hours_per_day(c._get_current_dated_attendances(today)),
                    precision_digits=2,
                )
            )
        )
        self.env.add_to_compute(self._fields["stored_hours_per_day"], to_refresh)
        to_refresh.flush_recordset(["stored_hours_per_day"])
        return to_refresh

    def _get_current_dated_attendances(self, day):
        """Attendances of the period valid on the day. Without one: the next
        period (planning entered before its start, or a gap between two
        periods), else the last one (the planning has ended)."""
        self.ensure_one()
        attendances = self.attendance_ids.filtered(
            lambda a: (
                a.day_period != "lunch" and not a.resource_id and not a.display_type
            )
        )
        current = attendances.filtered(
            lambda a: (
                (not a.date_from or a.date_from <= day)
                and (not a.date_to or a.date_to >= day)
            )
        )
        if not current and attendances:
            future = attendances.filtered(lambda a: a.date_from and a.date_from > day)
            if future:
                start = min(future.mapped("date_from"))
                return future.filtered(lambda a: a.date_from == start)
            last_start = max(a.date_from or date.min for a in attendances)
            current = attendances.filtered(
                lambda a: (a.date_from or date.min) == last_start
            )
        return current
